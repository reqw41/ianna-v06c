; vec_anim.asm — темп анимации воды и огня по нагрузке экрана.
; На экранах с крупным врагом (голем, огр, минотавр) тик перестаёт укладываться в frames_lock кадров:
; анимация идёт по тикам, тики становятся длиннее и неравномерными, вода дёргается. Там анимируем
; вчетверо реже (маска 3 вместо 1), на обычных экранах — как в оригинале, каждый 2-й тик.
;
; Критерий — НЕ длительность одного тика: в норме тики чередуются 3 и 7 кадров (в тик с анимацией
; работы вдвое больше), и по одиночному тику замедление включалось бы даже в начале уровня 1, где
; средний темп ровно номинальный. Считаем накопленный ДОЛГ по кадрам: тик длиннее номинала добавляет
; превышение, тик не длиннее — снимает единицу. На ровном экране долг колеблется у нуля, на тяжёлом
; растёт до насыщения и держит замедление (естественный гистерезис: выйти из него = 24 лёгких тика).
; Тяжёлым считается тик длиннее номинала НА ДВА кадра и больше: тик, в котором идёт анимация, штатно
; длиннее пустого (на уровне 1 они чередуются 4 и 6 кадров при номинале 5), и при пороге «номинал+1»
; долг зависал на уровне, куда его загнала загрузка уровня, вместо того чтобы спадать к нулю.
;
; ВАЖНО о размещении: код обязан лежать в ХВОСТЕ образа, после gen_data и хелперов z80rt. Перед
; fg_tile_lut в gen_data стоит выравнивание на страницу (ds ($+255)&$FF00-$), запаса до границы там
; всего 34 байта: 40 байт, добавленные ВЫШЕ, толкают LUT и весь хвост на страницу (+256 Б).
VEC_DEBT_MAX	equ 24		; насыщение долга (оно же длина гистерезиса в тиках)
VEC_DEBT_ON	equ 8		; с этого долга замедляем анимацию

vec_anim_calc:			; -> C = маска для animate_tile (1 = как в оригинале, 3 = вчетверо реже)
	ld hl,vec_tick_fc
	ld a,(FrameCounter)
	ld c,a
	sub (hl)		; A = сколько кадров занял прошлый тик
	ld (hl),c
	ld hl,frames_lock
	sub (hl)		; A = превышение над номиналом (со знаком)
	dec a			; ... сверх номинала+1: тик с анимацией штатно длиннее пустого, и по
	ld hl,vec_anim_debt	; чередованию 4/6 кадров долг иначе застревает на середине шкалы
	jp z,vad_ease
	jp m,vad_ease		; тик уложился
	add a,(hl)		; тяжёлый: долг += превышение (кадров в тике <= 12, переполнения нет)
	cp VEC_DEBT_MAX+1
	jp c,vad_store
	ld a,VEC_DEBT_MAX
vad_store:
	ld (hl),a
	jp vad_mask
vad_ease:
	ld a,(hl)
	or a
	jp z,vad_mask
	dec (hl)
vad_mask:
	ld a,(hl)
	cp VEC_DEBT_ON
	ld c,1			; долг мал — анимация каждый 2-й тик, как в оригинале
	ret c
	ld c,3			; экран не тянет — каждый 4-й
	ret
