;;; vec_turbo.asm — Вектор Турбо+ (резидент ROM). Разведка и план — docs/TURBO.md.
;;; Определение машины — vec_turbo_boot.asm (в string_area), ожидания контроллера — vec_fdd.asm.
; флаг vec_turbo — в окне vec_hi.asm (в резиденте до $6A00 места нет)

; Регистр управления дисковода (привод, сторона, мотор) и ожидание снятия BUSY. Резидент: зовут его и
; загрузчик набора, и загрузчик страниц героя.
vfl_ctl:			; регистр управления (привод, сторона, мотор) и ожидание снятия BUSY
	ld a,(vec_fdd_ctl)
	out ($1C),a
	in a,($1B)
	rrca
	jp c,vfl_ctl
	ld a,(vec_fdd_ctl)
	ret

; ---- Окно квазидиска на Турбо+ ----
; На Турбо+ окно порта 10h задаёт маска порта 42h, а биты 6 и 7 порта 10h не действуют: окно 8000..DFFF,
; которое на 06Ц включает бит 6 ($61 — карта уровня, $63 — оверлеи меню и паузы, загрузчик банков), там
; получается только маской 42h = 70h. В нечастых местах порт 10h пишется через rst 1 (обработчик по $0008,
; ставит vec_boot_init): out ($10),a и сюда. A = записанное значение, A и флаги целы.
; На 06Ц первый байт — ret; turbo_init ставит на его место push af.
vec_kv42:
	ret
	and $40
	ld a,$60
	jp z,vk42_o
	ld a,$70
vk42_o:
	out ($42),a
	pop af
	ret

; ---- Дождаться READY привода (бит 7 статуса ВГ93 = 0) после записи в 1Ch ----
; Меню (menu_ram, mb_read) читает слайды после простоя: мотор остановлен, запись 1Ch его включает, и READ
; SECTOR сразу за ней контроллер обрывает «не готов». BUSY при этом держится считанные такты — на 12 МГц
; (Турбо+) опрос его пропускал и ждал вечно под DI. Тайм-аут 8 x 65536 опросов (~2 с на 12 МГц).
vec_fdd_rdy:
	push bc
	push de
	ld d,8
	ld bc,0
vfdr_l:
	in a,($1B)
	rla
	jp nc,vfdr_ok
	dec bc
	ld a,b
	or c
	jp nz,vfdr_l
	dec d
	jp nz,vfdr_l
vfdr_ok:
	pop de
	pop bc
	ret
