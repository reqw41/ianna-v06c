; wpn_load.asm — подкачка страницы спрайтов героя под выбранное оружие (смена оружия в паузе).
;
; В квазидиске лежит ОДНА страница героя (банк 2): четыре по 23 616 Б туда не помещаются, а
; оригинал при смене оружия просто добавляет rom_offset_weapon к номеру банка (2 -> 2,4,5,6).
; Различаются у четырёх видов ровно кадры 14..36 (оружие в руке видно только в ударе), их и
; подкачиваем поверх банка 2 из библиотеки на дискете.
;
; Саму работу делает fdd_banks.asm (fb_wpn): он уже умеет читать библиотечный кусок и класть его
; в квазидиск стековым режимом. Здесь только обвязка, которой в игре нет:
;   * примитивы ВГ93 живут в ROM по $7E00 и при старте затираются rev256/таблицей слотов —
;     возвращаем их копию из набора (FDDCOPY) и после загрузки строим таблицы заново;
;   * сам fdd_banks лежит в наборе (стр.3) и работает из string_area — строки уровня оттуда
;     сохраняем в VRAM и возвращаем;
;   * VRAM на время загрузки — буфер ($8000 сжатый кусок, $C000 распакованный), поэтому экран
;     гасим палитрой, а после отдаём панель и поле на перерисовку оверлею паузы. Обратно палитру
;     зажигает ОН ЖЕ, когда перерисовка кончилась: сама подкачка идёт ~47 кадров, перерисовка поля
;     ещё ~40 (пул отдаёт супертайлы по бюджету кадра), и если зажечь экран сразу после чтения,
;     эти 0.8 с игрок видит буфер загрузки поверх недорисованного поля.
;   * дисковода может не быть (квазидиск заполнен снаружи, стенды, Emu80 без образа): проверяем
;     ВГ93 на NOT READY ДО того, как гасить экран и отдавать VRAM под буферы.
;
; Код исполняется ИЗ VRAM (WPN_ORG): свободного ОЗУ на 200 байт в игре нет — $0103 занят кодом
; старта, string_area строками уровня, а $7E00 нужен под примитивы загрузчика. Экран всё равно
; служит буфером, так что плоскость 3 под код и под спасённые строки — самое дешёвое место.
	include "menu_syms.asm"
KV_PORT		equ $10
KV_WIN_BANKS	equ $43		; окно $8000-$9FFF -> страница 3 набора: там лежит fdd_banks
FDD_REC		equ FDD_TAB + 64	; рецепт банков; в хвосте — шаблон записи страницы героя
FDD_WTMPL	equ FDD_REC + 120
SAVE_SRC	equ MB_ORG		; string_area: буфер сектора, таблицы, рецепт и сам fdd_banks
SAVE_LEN	equ FB_ORG + 512 - MB_ORG
SAVE_VRAM	equ $E000		; плоскость 3: загрузка её не трогает (буферы $8000 и $C000)

	org WPN_ORG
wl_go:
	di
	; --- примитивы ВГ93 обратно на $7E00 поверх rev256 и таблицы слотов ---
	; Это ПЕРВОЕ действие: пока дисковод не отозвался, экран и string_area трогать нельзя.
	; Таблицы всё равно строятся заново на любом выходе — их потеря ничего не стоит.
	ld a,LEVELTAB_PORT
	out (KV_PORT),a
	ld (vec_kv_shadow),a
	ld hl,FDDCOPY
	ld de,rev256
	ld bc,512
	call z_ldir
	xor a
	out (KV_PORT),a
	ld (vec_kv_shadow),a
	; --- есть ли дисковод? Бит 7 статуса ВГ93 = NOT READY, как в vec_fdd_load. Без этой проверки
	; запуск без дискеты (квазидиск снаружи, Emu80, стенды) гасил экран, отдавал VRAM под буферы
	; и звал загрузчик, которому неоткуда читать: картинка разрушалась, а страница не менялась.
	ld a,$34
	ld (vec_fdd_ctl),a
	call vfl_ctl
	in a,($1B)
	and $80
	jp nz,wl_bail
	; --- экран гасим палитрой: дальше VRAM работает буфером ---
	ld c,0
wl_pal:
	ld a,c
	out ($02),a
	xor a
	out ($0C),a
	out ($0C),a
	out ($0C),a
	inc c
	ld a,c
	cp 16
	jp nz,wl_pal
	; --- строки уровня из string_area в VRAM: их место займут буфер сектора и загрузчик ---
	ld hl,SAVE_SRC
	ld de,SAVE_VRAM
	ld bc,SAVE_LEN
	call z_ldir
	; --- загрузчик банков из набора в string_area ---
	ld a,KV_WIN_BANKS
	out (KV_PORT),a
	ld (vec_kv_shadow),a
	ld hl,FDD_BANKCODE
	ld de,FB_ORG
	ld bc,512
	call z_ldir
	xor a
	out (KV_PORT),a
	ld (vec_kv_shadow),a
	; --- рецепт: банков нет (они на месте), только страница героя. Шаблон записи собираем из
	; таблицы банков в ОЗУ: при загрузке уровня её ещё нет и там шаблон кладёт build_levels ---
	ld (FDD_REC),a
	ld a,(vec_bank_tab)		; порт квазидиска банка 2
	ld (FDD_WTMPL),a
	ld a,$80			; кадр 14: 14*576 = $1F80
	ld (FDD_WTMPL+1),a
	ld a,(vec_bank_tab+1)		; старший байт базы банка
	add a,$1F
	ld (FDD_WTMPL+2),a
	ei				; как при загрузке уровня: чтение идёт с разрешёнными прерываниями
	call FB_ORG
	; --- строки уровня на место, таблицы заново ---
	di
	ld hl,SAVE_VRAM
	ld de,SAVE_SRC
	ld bc,SAVE_LEN
	call z_ldir
	; ПАЛИТРУ ЗДЕСЬ НЕ ВОЗВРАЩАЕМ. Перерисовка поля идёт ещё ~40 кадров (пул отдаёт супертайлы
	; по бюджету кадра), и если зажечь экран сразу, эти 0.8 с игрок видит буфер загрузки поверх
	; недорисованного поля — та самая «разрушенная картинка». Флаг ставит оверлей паузы, когда
	; панель, поле и рамка уже на месте (pause_ovl.asm, pz_weapon).
wl_bail:
	ei
	call vec_init_rev256
	call vec_slot_init
	ret
