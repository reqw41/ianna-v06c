; vec_boot.asm — заголовок ROM: точка входа по $0100 и константы.
; Загрузка ROM по $0100 (vector06js ?sword.rom, MiSTer .rom).
; Дальше в образе идут переменные (org $0200, string_area строго по $0200 —
; на этот адрес перенесены указатели скриптов уровня), затем данные демо
; (org $1600, только DEMO) и код (vec_main.asm и далее).

	org $0100
	jp vec_start

VDP_NY		equ 10		; смещение NY в буфере команды (как в vdp.asm)
FRAMES_LOCK	equ 5		; PAL: игровой тик = 5 кадров
