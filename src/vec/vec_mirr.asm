; vec_mirr.asm — подмена кадра спрайта на готовую зеркальную копию.
; Зеркальный блит разворачивает КАЖДЫЙ байт строки через таблицу rev256 заново на каждом тике и
; стоит вшестеро дороже прямого (профиль экрана 4,5: dspm_row 20.9 % тика против dsp_row 3.4 %).
; Кадр меняется почти каждый тик, но разных кадров в обороте 7..10 — цикл анимации повторяется,
; поэтому копии приготовлены заранее (build_edd, MIRRORS) и лежат в той же странице квазидиска,
; что и банк: порт менять не надо, дальше идёт обычный прямой блит.
;
; Страницу сверяем обязательно: одни и те же адреса в другой странице принадлежат другому банку
; (камень лежит в стр.3 по $2800-$8440 и попадал бы в диапазон кадров мумии).
;
; ВАЖНО о размещении: файл подключается в ХВОСТ образа, после хелперов z80rt. Перед fg_tile_lut в
; gen_data стоит выравнивание на страницу, и запаса до границы там считанные байты — код, добавленный
; выше, толкает LUT и весь хвост образа на +256 Б (ловилось дважды, см. ANALYSIS.md).

vec_mirror_src:			; портит A, BC, DE, HL; вызывается один раз на спрайт
	ld a,(vec_spr_dir)
	or a
	ret z			; спрайт и так прямой
	ld hl,vm_tab
	ld b,6			; записей в таблице (build_edd.MIRROR_SLOTS)
vm_loop:
	push hl			; начало записи — по нему шагаем к следующей
	ld a,(vec_spr_port)
	cp (hl)
	jp nz,vm_next
	inc hl
	ld a,(vec_spr_src+1)	; старший байт адреса кадра
	cp (hl)
	jp c,vm_next		; ниже начала банка
	inc hl
	cp (hl)
	jp nc,vm_next		; выше зеркалированной части банка
	inc hl
	ld e,(hl)
	inc hl
	ld d,(hl)		; DE = смещение до копии
	inc hl
	ld a,(hl)
	ld (vec_spr_port),a	; копии могут лежать в другой странице (орк: банк в стр.2, копии в стр.3)
	pop hl
vm_hit:				; метка для профиля: подмена состоялась
	ld hl,(vec_spr_src)
	add hl,de
	ld (vec_spr_src),hl
	xor a
	ld (vec_spr_dir),a	; дальше — обычный прямой блит
	ret
vm_next:
	pop hl
	ld de,6
	add hl,de
	dec b
	jp nz,vm_loop
	ret

; Таблица vm_tab лежит в ОЗУ и приходит из набора уровня (build_edd.mirror_table): её состав
; зависит от уровня, а ROM теперь общий для всех.
