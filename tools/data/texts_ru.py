def build_block(en_block, nstrings, nscripts, strings):
    """Блок строк уровня с новыми строками: [ptr][ptr][таблица строк][строки][таблица скриптов][скрипты];
    скрипты копируются как есть, их таблица сдвигается. Указатели абсолютные от $C000 (как в MSX)."""
    BASE = 0xC000
    b = en_block
    rd = lambda o: b[o] | (b[o+1] << 8)
    st = rd(0) - BASE; sc = rd(2) - BASE
    assert st == 4 and len(strings) == nstrings, (st, len(strings), nstrings)
    tail = b[sc:]                       # таблица скриптов + тела
    out = bytearray(4 + 2*nstrings)
    ptrs = []
    for s in strings:
        ptrs.append(len(out)); out += encode(s) + b'\0'
    new_sc = len(out)
    delta = new_sc - sc
    def wr(o, v): out[o] = v & 0xff; out[o+1] = (v >> 8) & 0xff
    wr(0, BASE + 4); wr(2, BASE + new_sc)
    for i, p in enumerate(ptrs): wr(4 + 2*i, BASE + p)
    out += tail
    for i in range(nscripts):
        o = new_sc + 2*i; wr(o, rd(sc + 2*i) + delta)
    return bytes(out)

