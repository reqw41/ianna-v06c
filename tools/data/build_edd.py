    from texts_ru import LEVEL_TEXTS, build_block        # русский блок строк на месте испанского (language=0)
    info['strings']['es'] = build_block(info['strings']['en'], info['nstrings'], info['nscripts'], LEVEL_TEXTS[level_no])
