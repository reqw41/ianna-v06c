def bank_tab_lines(banks):
    by = {b: (pg, base) for b, pg, base, _ in banks}
    lines = ['; Таблица банков MSX 2..21 -> (порт стека квазидиска, старший байт базы) кадров спрайтов; неизвестные -> стр.0 $0000',
             'vec_bank_tab:']
    for b in range(2, 22):
        pg, base = by.get(b, (0, 0))
